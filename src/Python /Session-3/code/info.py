# name , age is parameters
def user_info(name, age):
    '''
    This function takes name and age as parameters and prints them in a formatted string.

    Args:
        param_name (str): The name of the user.
        param_age (int): The age of the user.

    Returns:
        return_type: print the user information in a formatted string.

    Example:
        user_info("John", 30)        
    '''

    print(f"my name is {name} and my age is {age}")
